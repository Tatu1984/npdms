// Helper function to search IPC sections
export function searchIPCSections(query: string): IPCSection[] {
  const lowerQuery = query.toLowerCase();
  return IPC_SECTIONS.filter(
    (section) =>
      section.code.toLowerCase().includes(lowerQuery) ||
      section.title.toLowerCase().includes(lowerQuery) ||
      section.description.toLowerCase().includes(lowerQuery) ||
      section.category.toLowerCase().includes(lowerQuery)
  );
}

// Helper function to get sections by category
export function getIPCSectionsByCategory(category: IPCCategory): IPCSection[] {
  return IPC_SECTIONS.filter((section) => section.category === category);
}

// Helper function to get section by code
export function getIPCSectionByCode(code: string): IPCSection | undefined {
  return IPC_SECTIONS.find((section) => section.code === code);
}

